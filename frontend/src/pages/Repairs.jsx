import React, { useState, useEffect } from 'react'
import { useLocation } from 'react-router-dom'
import {
  Box,
  Paper,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  Button,
  IconButton,
  TextField,
  InputAdornment,
  Chip,
  Dialog,
  DialogTitle,
  DialogContent,
  DialogActions,
  MenuItem,
  Grid,
  Typography,
  LinearProgress,
  FormControl,
  InputLabel,
  Select,
  Alert,
  Divider,
  Tooltip,
  Card,
  CardContent,
  Fade,
  FormHelperText, // ✅ ADDED
} from '@mui/material'
import {
  Add,
  Search,
  Edit,
  Delete,
  Visibility,
  Close,
  CheckCircle,
  Refresh,
  Person,
  AccessTime,
  Description,
  MedicalServices,
  Assignment,
  Check,
  Warning,
  Error as ErrorIcon,
  Pending,
  Verified,
  Inventory,
  Add as AddIcon,
  Remove as RemoveIcon,
  Save,
  Engineering as EngineeringIcon,
  AdminPanelSettings
} from '@mui/icons-material'
import { repairService, errorService, equipmentService } from '../api/services'
import { toast } from 'react-toastify'
import { useSelector } from 'react-redux'
import AccessDenied from '../components/Auth/AccessDenied'

const Repairs = () => {
  const { user } = useSelector((state) => state.auth)
  const location = useLocation()
  
  // ✅ HOSPITAL_ADMIN - Access Denied
  if (user?.role === 'HOSPITAL_ADMIN') {
    return <AccessDenied message="Hospital Administrators cannot access Repairs." />
  }
  
  const isSuperAdmin = user?.role === 'SUPER_ADMIN'
  const isEngineer = user?.role === 'ENGINEER'
  
  // ✅ PERMISSIONS
  // ✅ ENGINEER: View ALL repairs, Create (Upload Solution) ONLY - NO Edit/Delete
  // ✅ SUPER_ADMIN: View ALL, Edit ANY, Delete ANY
  const canCreate = isEngineer || isSuperAdmin // ✅ Both can create
  const canDelete = isSuperAdmin // ✅ ONLY Super Admin can delete
  const canView = isEngineer || isSuperAdmin // ✅ Both can view
  
  // ✅ Only SUPER_ADMIN can edit ANY repair
  const canEdit = (repair) => {
    return isSuperAdmin // ✅ Only Super Admin can edit
  }
  
  // ✅ Only SUPER_ADMIN can update status
  const canUpdateStatus = (repair) => {
    return isSuperAdmin // ✅ Only Super Admin can update status
  }

  const [repairs, setRepairs] = useState([])
  const [errors, setErrors] = useState([])
  const [equipment, setEquipment] = useState([])
  const [loading, setLoading] = useState(true)
  const [searchTerm, setSearchTerm] = useState('')
  const [openDialog, setOpenDialog] = useState(false)
  const [openViewDialog, setOpenViewDialog] = useState(false)
  const [editingRepair, setEditingRepair] = useState(null)
  const [viewingRepair, setViewingRepair] = useState(null)
  const [filters, setFilters] = useState({ status: '' })
  
  const [highlightedRepair, setHighlightedRepair] = useState(null)
  const [highlightTimer, setHighlightTimer] = useState(null)

  const [showSparePartsFields, setShowSparePartsFields] = useState(false)
  const [sparePartsList, setSparePartsList] = useState([])
  const [sparePartForm, setSparePartForm] = useState({
    part_name: '',
    part_number: '',
    brand: '',
    quantity: 1,
    unit_cost: '',
    total_cost: '',
    installation_notes: ''
  })

  const [formData, setFormData] = useState({
    error_log_id: '',
    equipment_id: '',
    engineer_id: '',
    engineer_name: '',
    root_cause: '',
    problem_analysis: '',
    corrective_action: '',
    repair_procedure: '',
    solution_description: '',
    time_taken: '',
    spare_part_used: 'No',
    remarks: '',
    status: 'Pending'
  })

  useEffect(() => {
    fetchData()
    
    if (location.state?.autoGenerated || location.state?.fromErrorAssignment) {
      const { newRepairId, engineerName, errorId, errorTitle, equipmentName } = location.state
      
      console.log('🔧 Repair created from error assignment:', {
        repairId: newRepairId,
        engineerName: engineerName,
        errorId: errorId,
        errorTitle: errorTitle,
        equipmentName: equipmentName
      })
      
      if (engineerName) {
        toast.success(`🔧 New repair created for engineer: ${engineerName}`)
      } else {
        toast.success('🔧 New repair created from error assignment!')
      }
      
      if (newRepairId) {
        setHighlightedRepair(newRepairId)
        
        setTimeout(() => {
          const element = document.getElementById(`repair-${newRepairId}`)
          if (element) {
            element.scrollIntoView({ behavior: 'smooth', block: 'center' })
            element.style.transition = 'all 0.5s ease'
            element.style.border = '3px solid #28a745'
            element.style.backgroundColor = '#f0fff4'
            element.style.boxShadow = '0 0 20px rgba(40, 167, 69, 0.3)'
            
            setTimeout(() => {
              element.style.backgroundColor = '#f8fff8'
            }, 1000)
          }
        }, 600)
        
        const timer = setTimeout(() => {
          setHighlightedRepair(null)
          const element = document.getElementById(`repair-${newRepairId}`)
          if (element) {
            element.style.border = 'none'
            element.style.backgroundColor = 'transparent'
            element.style.boxShadow = 'none'
          }
        }, 8000)
        setHighlightTimer(timer)
      }
    }
    
    return () => {
      if (highlightTimer) {
        clearTimeout(highlightTimer)
      }
    }
  }, [location])

  useEffect(() => {
    if (formData.error_log_id) {
      const selectedError = errors.find(e => e.id === parseInt(formData.error_log_id))
      if (selectedError) {
        console.log('🔄 Auto-filling from error:', selectedError)
        setFormData(prev => ({
          ...prev,
          equipment_id: selectedError.equipment_id || '',
          root_cause: selectedError.error_description || selectedError.error_title || '',
          problem_analysis: selectedError.error_description || '',
        }))
      }
    }
  }, [formData.error_log_id, errors])

  const fetchData = async () => {
    setLoading(true)
    try {
      const [repairsRes, errorsRes, equipmentRes] = await Promise.all([
        repairService.getAll(),
        errorService.getAll(),
        equipmentService.getAll()
      ])
      setRepairs(repairsRes.data.repairs || [])
      setErrors(errorsRes.data.errors || [])
      setEquipment(equipmentRes.data.equipment || [])
    } catch (error) {
      console.error('❌ Fetch error:', error)
      toast.error('Failed to fetch data')
    } finally {
      setLoading(false)
    }
  }

  // ==================== CRUD HANDLERS ====================
  const handleOpenDialog = (repair = null) => {
    // ✅ Both Engineer and Super Admin can create
    if (!isEngineer && !isSuperAdmin) {
      toast.error('You do not have permission to create repairs')
      return
    }
    
    // ✅ If editing, check if user is Super Admin
    if (repair && !isSuperAdmin) {
      toast.error('Only Super Admin can edit repairs')
      return
    }
    
    if (repair) {
      setEditingRepair(repair)
      setFormData({
        error_log_id: repair.error_log_id || '',
        equipment_id: repair.equipment_id || '',
        engineer_id: repair.engineer_id || '',
        engineer_name: repair.engineer_name || '',
        root_cause: repair.root_cause || '',
        problem_analysis: repair.problem_analysis || '',
        corrective_action: repair.corrective_action || '',
        repair_procedure: repair.repair_procedure || '',
        solution_description: repair.solution_description || '',
        time_taken: repair.time_taken || '',
        spare_part_used: repair.spare_part_used || 'No',
        remarks: repair.remarks || '',
        status: repair.status || 'Pending'
      })
      setShowSparePartsFields(repair.spare_part_used === 'Yes')
      setSparePartsList(repair.spare_parts || [])
    } else {
      setEditingRepair(null)
      setFormData({
        error_log_id: '',
        equipment_id: '',
        engineer_id: user?.id || '',
        engineer_name: user?.full_name || '',
        root_cause: '',
        problem_analysis: '',
        corrective_action: '',
        repair_procedure: '',
        solution_description: '',
        time_taken: '',
        spare_part_used: 'No',
        remarks: '',
        status: 'Pending'
      })
      setShowSparePartsFields(false)
      setSparePartsList([])
    }
    setOpenDialog(true)
  }

  const handleCloseDialog = () => {
    setOpenDialog(false)
    setEditingRepair(null)
    setShowSparePartsFields(false)
    setSparePartsList([])
  }

  const handleView = (repair) => {
    setViewingRepair(repair)
    setOpenViewDialog(true)
  }

  const handleCloseView = () => {
    setOpenViewDialog(false)
    setViewingRepair(null)
  }

  // ==================== FORM HANDLERS ====================
  const handleFormChange = (e) => {
    const { name, value } = e.target
    
    if (name === 'spare_part_used') {
      setShowSparePartsFields(value === 'Yes')
      if (value === 'No') {
        setSparePartsList([])
      }
    }
    
    setFormData({
      ...formData,
      [name]: value
    })
  }

  // ==================== SPARE PARTS HANDLERS ====================
  const handleSparePartChange = (e) => {
    const { name, value } = e.target
    setSparePartForm(prev => ({
      ...prev,
      [name]: value
    }))
  }

  const handleAddSparePart = () => {
    if (!sparePartForm.part_name || sparePartForm.part_name.trim() === '') {
      toast.error('Please enter part name')
      return
    }

    const quantity = parseInt(sparePartForm.quantity) || 1
    const unitCost = parseFloat(sparePartForm.unit_cost) || 0
    const totalCost = quantity * unitCost

    const newPart = {
      id: Date.now(),
      part_name: sparePartForm.part_name.trim(),
      part_number: sparePartForm.part_number || '',
      brand: sparePartForm.brand || '',
      quantity: quantity,
      unit_cost: unitCost,
      total_cost: totalCost,
      installation_notes: sparePartForm.installation_notes || ''
    }

    setSparePartsList(prev => [...prev, newPart])
    setSparePartForm({
      part_name: '',
      part_number: '',
      brand: '',
      quantity: 1,
      unit_cost: '',
      total_cost: '',
      installation_notes: ''
    })
    toast.success('Spare part added')
  }

  const handleRemoveSparePart = (id) => {
    setSparePartsList(prev => prev.filter(p => p.id !== id))
    toast.info('Spare part removed')
  }

  // ==================== SUBMIT ====================
  const handleSubmit = async () => {
    // ✅ Both Engineer and Super Admin can submit
    if (!isEngineer && !isSuperAdmin) {
      toast.error('You do not have permission to create repairs')
      return
    }
    
    try {
      if (!formData.error_log_id) {
        toast.error('Please select an error to repair')
        return
      }

      const payload = {
        error_log_id: parseInt(formData.error_log_id),
        equipment_id: formData.equipment_id ? parseInt(formData.equipment_id) : null,
        engineer_id: user?.id || null,
        engineer_name: user?.full_name || formData.engineer_name || '',
        root_cause: formData.root_cause || '',
        problem_analysis: formData.problem_analysis || '',
        corrective_action: formData.corrective_action || '',
        repair_procedure: formData.repair_procedure || '',
        solution_description: formData.solution_description || '',
        time_taken: formData.time_taken ? parseInt(formData.time_taken) : 0,
        spare_part_used: formData.spare_part_used || 'No',
        spare_parts: formData.spare_part_used === 'Yes' ? sparePartsList : [],
        remarks: formData.remarks || '',
        status: formData.status || 'Pending'
      }

      if (editingRepair) {
        await repairService.update(editingRepair.id, payload)
        toast.success('Repair updated successfully')
      } else {
        await repairService.create(payload)
        toast.success('Repair recorded successfully')
        
        if (formData.error_log_id) {
          await errorService.update(formData.error_log_id, { status: 'In Progress' })
        }
      }
      fetchData()
      handleCloseDialog()
    } catch (error) {
      console.error('❌ Submit error:', error)
      toast.error(error.response?.data?.message || 'Operation failed')
    }
  }

  const handleDelete = async (id) => {
    // ✅ ONLY Super Admin can delete
    if (!isSuperAdmin) {
      toast.error('Only Super Admin can delete repairs')
      return
    }
    
    const repairToDelete = repairs.find(r => r.id === id)
    const confirmMessage = `🗑️ DELETE REPAIR\n\n` +
      `Are you sure you want to delete this repair record?\n\n` +
      `📌 Equipment: ${repairToDelete?.equipment_name || 'N/A'}\n` +
      `🔧 Engineer: ${repairToDelete?.engineer_name || 'N/A'}\n` +
      `📊 Status: ${repairToDelete?.status || 'N/A'}\n` +
      `📅 Date: ${repairToDelete?.repair_date ? new Date(repairToDelete.repair_date).toLocaleDateString() : 'N/A'}\n\n` +
      `❌ This action cannot be undone!`
    
    if (!window.confirm(confirmMessage)) {
      return
    }
    
    try {
      await repairService.delete(id)
      toast.success('🗑️ Repair deleted successfully')
      fetchData()
    } catch (error) {
      console.error('❌ Delete error:', error)
      toast.error('Failed to delete repair')
    }
  }

  const isHighlighted = (repairId) => {
    return highlightedRepair === repairId
  }

  // ✅ Everyone can see ALL repairs
  const filteredRepairs = repairs.filter(repair => {
    const matchesSearch = repair.equipment_name?.toLowerCase().includes(searchTerm.toLowerCase()) ||
                          repair.engineer_name?.toLowerCase().includes(searchTerm.toLowerCase()) ||
                          repair.root_cause?.toLowerCase().includes(searchTerm.toLowerCase())
    const matchesStatus = !filters.status || repair.status === filters.status
    return matchesSearch && matchesStatus
  })

  if (loading) {
    return <LinearProgress />
  }

  return (
    <Box>
      {/* Header */}
      <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', mb: 3, flexWrap: 'wrap', gap: 2 }}>
        <Box sx={{ display: 'flex', alignItems: 'center', gap: 2 }}>
          <Typography variant="h5" sx={{ fontWeight: 700, color: '#2C3E50' }}>
            Repairs
          </Typography>
          {isEngineer && (
            <Chip 
              icon={<EngineeringIcon sx={{ fontSize: 16 }} />}
              label="Engineer Mode - View & Upload Only" 
              size="small" 
              color="info" 
            />
          )}
          {isSuperAdmin && (
            <Chip 
              icon={<AdminPanelSettings sx={{ fontSize: 16 }} />}
              label="Super Admin (Full Control)" 
              size="small" 
              color="warning" 
            />
          )}
        </Box>
        <Box sx={{ display: 'flex', gap: 1 }}>
          <Button
            variant="outlined"
            onClick={fetchData}
            size="small"
          >
            Refresh
          </Button>
          {/* ✅ Both Engineer and Super Admin can create repairs */}
          {(isEngineer || isSuperAdmin) && (
            <Button
              variant="contained"
              onClick={() => handleOpenDialog()}
              sx={{ bgcolor: '#0B5FA5', '&:hover': { bgcolor: '#084a8a' } }}
            >
              Record Repair
            </Button>
          )}
        </Box>
      </Box>

      {/* Stats Cards */}
      <Grid container spacing={2} sx={{ mb: 3 }}>
        <Grid item xs={6} sm={3}>
          <Card sx={{ borderRadius: 2 }}>
            <CardContent sx={{ textAlign: 'center', py: 2 }}>
              <Typography variant="h4" color="#0B5FA5" fontWeight={700}>
                {repairs.length}
              </Typography>
              <Typography variant="body2" color="textSecondary">Total Repairs</Typography>
            </CardContent>
          </Card>
        </Grid>
        <Grid item xs={6} sm={3}>
          <Card sx={{ borderRadius: 2, bgcolor: '#fff3e0' }}>
            <CardContent sx={{ textAlign: 'center', py: 2 }}>
              <Typography variant="h4" color="#ff9800" fontWeight={700}>
                {repairs.filter(r => r.status === 'Pending' || r.status === 'In Progress' || r.status === 'Assigned' || r.status === 'Accepted').length}
              </Typography>
              <Typography variant="body2" color="textSecondary">Active</Typography>
            </CardContent>
          </Card>
        </Grid>
        <Grid item xs={6} sm={3}>
          <Card sx={{ borderRadius: 2, bgcolor: '#e8f5e9' }}>
            <CardContent sx={{ textAlign: 'center', py: 2 }}>
              <Typography variant="h4" color="#28a745" fontWeight={700}>
                {repairs.filter(r => r.status === 'Completed' || r.status === 'Verified' || r.status === 'Resolved').length}
              </Typography>
              <Typography variant="body2" color="textSecondary">Completed</Typography>
            </CardContent>
          </Card>
        </Grid>
        <Grid item xs={6} sm={3}>
          <Card sx={{ borderRadius: 2, bgcolor: '#e3f2fd' }}>
            <CardContent sx={{ textAlign: 'center', py: 2 }}>
              <Typography variant="h4" color="#0B5FA5" fontWeight={700}>
                {new Set(repairs.map(r => r.equipment_name)).size}
              </Typography>
              <Typography variant="body2" color="textSecondary">Equipment Repaired</Typography>
            </CardContent>
          </Card>
        </Grid>
      </Grid>

      {/* Info Alerts */}
      {isEngineer && (
        <Alert severity="info" sx={{ mb: 2 }}>
          <Typography variant="body2">
            <strong>🔧 Engineer Mode:</strong> You can view all repairs and <strong>upload new solutions</strong>. 
            Only <strong>Super Admin</strong> can edit or delete repairs.
          </Typography>
        </Alert>
      )}

      {isSuperAdmin && (
        <Alert severity="warning" sx={{ mb: 2 }}>
          <Typography variant="body2">
            <strong>👑 Super Admin:</strong> You have full control. You can view, create, edit, delete, and update status of any repair.
          </Typography>
        </Alert>
      )}

      {/* Search & Filters */}
      <Paper sx={{ p: 2, mb: 3, borderRadius: 2 }}>
        <Box sx={{ display: 'flex', gap: 2, flexWrap: 'wrap', alignItems: 'center' }}>
          <TextField
            size="small"
            placeholder="Search by equipment, engineer or root cause..."
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            sx={{ flexGrow: 1, minWidth: 200 }}
          />
          <FormControl size="small" sx={{ minWidth: 150 }}>
            <InputLabel>Status</InputLabel>
            <Select
              value={filters.status}
              onChange={(e) => setFilters({ ...filters, status: e.target.value })}
              label="Status"
            >
              <MenuItem value="">All</MenuItem>
              <MenuItem value="Pending">Pending</MenuItem>
              <MenuItem value="Assigned">Assigned</MenuItem>
              <MenuItem value="Accepted">Accepted</MenuItem>
              <MenuItem value="In Progress">In Progress</MenuItem>
              <MenuItem value="Waiting for Spare Parts">Waiting for Spare Parts</MenuItem>
              <MenuItem value="Testing">Testing</MenuItem>
              <MenuItem value="Completed">Completed</MenuItem>
              <MenuItem value="Verified">Verified</MenuItem>
              <MenuItem value="Resolved">Resolved</MenuItem>
              <MenuItem value="Closed">Closed</MenuItem>
            </Select>
          </FormControl>
        </Box>
      </Paper>

      {/* Table */}
      <TableContainer component={Paper} sx={{ borderRadius: 2 }}>
        <Table>
          <TableHead sx={{ bgcolor: '#0B5FA5' }}>
            <TableRow>
              <TableCell sx={{ color: 'white', fontWeight: 600 }}>Equipment</TableCell>
              <TableCell sx={{ color: 'white', fontWeight: 600 }}>Engineer</TableCell>
              <TableCell sx={{ color: 'white', fontWeight: 600 }}>Issue</TableCell>
              <TableCell sx={{ color: 'white', fontWeight: 600 }}>Status</TableCell>
              <TableCell sx={{ color: 'white', fontWeight: 600 }}>Time</TableCell>
              <TableCell sx={{ color: 'white', fontWeight: 600 }}>Spare Used</TableCell>
              <TableCell sx={{ color: 'white', fontWeight: 600 }}>Date</TableCell>
              <TableCell sx={{ color: 'white', fontWeight: 600, textAlign: 'center' }}>Actions</TableCell>
            </TableRow>
          </TableHead>
          <TableBody>
            {filteredRepairs.length === 0 ? (
              <TableRow>
                <TableCell colSpan={8} align="center">
                  <Typography variant="body1" sx={{ py: 4, color: '#6c757d' }}>
                    No repairs found
                  </Typography>
                </TableCell>
              </TableRow>
            ) : (
              filteredRepairs.map((repair) => {
                const highlighted = isHighlighted(repair.id)
                const isOwnRepair = isEngineer && (repair.engineer_id === user?.id || repair.engineer_name === user?.full_name)
                
                return (
                  <TableRow 
                    key={repair.id} 
                    id={`repair-${repair.id}`}
                    hover
                    sx={{
                      backgroundColor: highlighted ? 'rgba(40, 167, 69, 0.15)' : 'inherit',
                      transition: 'background-color 0.5s ease, border 0.3s ease, box-shadow 0.3s ease',
                      '&:hover': {
                        backgroundColor: highlighted ? 'rgba(40, 167, 69, 0.25)' : 'rgba(0, 0, 0, 0.04)'
                      }
                    }}
                  >
                    <TableCell>
                      <Box sx={{ display: 'flex', alignItems: 'center', gap: 1 }}>
                        <Typography variant="body2" fontWeight={500}>
                          {repair.equipment_name || 'N/A'}
                        </Typography>
                        {highlighted && (
                          <Typography variant="caption" color="success.main" sx={{ fontWeight: 600 }}>
                            NEW
                          </Typography>
                        )}
                        {isOwnRepair && (
                          <Chip 
                            label="My Repair" 
                            size="small" 
                            color="primary" 
                            sx={{ height: 18, fontSize: '9px' }}
                          />
                        )}
                      </Box>
                    </TableCell>
                    <TableCell>
                      <Typography variant="body2">
                        {repair.engineer_name || 'N/A'}
                      </Typography>
                    </TableCell>
                    <TableCell>
                      <Typography variant="body2" noWrap sx={{ maxWidth: 150 }}>
                        {repair.root_cause || '-'}
                      </Typography>
                    </TableCell>
                    <TableCell>
                      <Chip 
                        label={repair.status} 
                        size="small"
                        color={
                          repair.status === 'Completed' || repair.status === 'Verified' || repair.status === 'Resolved' ? 'success' :
                          repair.status === 'Pending' ? 'default' :
                          repair.status === 'In Progress' ? 'info' :
                          repair.status === 'Assigned' || repair.status === 'Accepted' ? 'primary' :
                          repair.status === 'Waiting for Spare Parts' ? 'warning' :
                          repair.status === 'Testing' ? 'secondary' :
                          repair.status === 'Closed' ? 'default' : 'default'
                        }
                        sx={{ height: 22, fontSize: '11px' }}
                      />
                    </TableCell>
                    <TableCell>
                      {repair.time_taken ? `${repair.time_taken}m` : '-'}
                    </TableCell>
                    <TableCell>
                      <Typography variant="body2">
                        {repair.spare_part_used || 'No'}
                      </Typography>
                    </TableCell>
                    <TableCell>
                      <Typography variant="body2">
                        {repair.repair_date ? new Date(repair.repair_date).toLocaleDateString() : 
                         repair.created_at ? new Date(repair.created_at).toLocaleDateString() : '-'}
                      </Typography>
                    </TableCell>
                    <TableCell align="center">
                      <Box sx={{ display: 'flex', justifyContent: 'center', gap: 0.5 }}>
                        <Tooltip title="View Details">
                          <IconButton size="small" color="primary" onClick={() => handleView(repair)}>
                            <Visibility fontSize="small" />
                          </IconButton>
                        </Tooltip>
                        
                        {/* ✅ ONLY Super Admin can edit ANY repair */}
                        {isSuperAdmin && (
                          <Tooltip title="Edit Repair">
                            <IconButton size="small" color="info" onClick={() => handleOpenDialog(repair)}>
                              <Edit fontSize="small" />
                            </IconButton>
                          </Tooltip>
                        )}
                        
                        {/* ✅ ONLY Super Admin can delete */}
                        {isSuperAdmin && (
                          <Tooltip title="Delete">
                            <IconButton size="small" color="error" onClick={() => handleDelete(repair.id)}>
                              <Delete fontSize="small" />
                            </IconButton>
                          </Tooltip>
                        )}
                      </Box>
                    </TableCell>
                  </TableRow>
                )
              })
            )}
          </TableBody>
        </Table>
      </TableContainer>

      {/* Add/Edit Dialog */}
      <Dialog open={openDialog} onClose={handleCloseDialog} maxWidth="md" fullWidth>
        <DialogTitle sx={{ bgcolor: '#0B5FA5', color: 'white' }}>
          <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
            <Box sx={{ display: 'flex', alignItems: 'center', gap: 1 }}>
              <Typography variant="h6" fontWeight={600}>
                {editingRepair ? 'Edit Repair' : 'Record Repair'}
              </Typography>
              {isEngineer && !editingRepair && (
                <Chip label="Engineer - Upload Solution" size="small" color="info" sx={{ bgcolor: '#2196f3' }} />
              )}
              {isSuperAdmin && (
                <Chip label="Super Admin" size="small" color="warning" sx={{ bgcolor: '#ff9800' }} />
              )}
            </Box>
            <IconButton onClick={handleCloseDialog} sx={{ color: 'white' }}>
              <Close />
            </IconButton>
          </Box>
        </DialogTitle>
        <DialogContent dividers>
          <Grid container spacing={2} sx={{ mt: 0 }}>
            <Grid item xs={12}>
              <Alert severity="info">
                <Typography variant="body2">
                  <strong>Auto-fill Feature:</strong> Selecting an error will automatically fill the equipment and root cause fields.
                  {isEngineer && !editingRepair && (
                    <span style={{ display: 'block', marginTop: '4px' }}>
                      🔧 You are uploading a new repair solution. Only Super Admin can edit existing repairs.
                    </span>
                  )}
                </Typography>
              </Alert>
            </Grid>

            <Grid item xs={12}>
              <FormControl fullWidth required>
                <InputLabel>Select Error to Repair *</InputLabel>
                <Select
                  name="error_log_id"
                  value={formData.error_log_id}
                  onChange={handleFormChange}
                  label="Select Error to Repair *"
                >
                  <MenuItem value="">Select Error</MenuItem>
                  {errors.filter(e => e.status === 'Pending' || e.status === 'In Progress').map(err => (
                    <MenuItem key={err.id} value={err.id}>
                      {err.error_title} - {err.equipment_name} ({err.status})
                    </MenuItem>
                  ))}
                </Select>
              </FormControl>
            </Grid>

            <Grid item xs={12} md={6}>
              <FormControl fullWidth>
                <InputLabel>Equipment (Auto-filled)</InputLabel>
                <Select
                  name="equipment_id"
                  value={formData.equipment_id}
                  onChange={handleFormChange}
                  label="Equipment (Auto-filled)"
                >
                  <MenuItem value="">Select Equipment</MenuItem>
                  {equipment.map(item => (
                    <MenuItem key={item.id} value={item.id}>
                      {item.name} - {item.model || 'N/A'}
                    </MenuItem>
                  ))}
                </Select>
                {formData.equipment_id && (
                  <Typography variant="caption" color="success.main">
                    ✅ Auto-filled from selected error
                  </Typography>
                )}
              </FormControl>
            </Grid>

            <Grid item xs={12} md={6}>
              <TextField
                fullWidth
                label="Engineer Name"
                name="engineer_name"
                value={formData.engineer_name || user?.full_name || ''}
                onChange={handleFormChange}
                placeholder="Name of engineer who fixed"
                disabled={!isSuperAdmin}
              />
            </Grid>

            <Grid item xs={12}>
              <Divider sx={{ my: 1 }} />
              <Typography variant="subtitle2" fontWeight={600} color="primary" gutterBottom>
                Problem Analysis
              </Typography>
            </Grid>
            <Grid item xs={12}>
              <TextField
                fullWidth
                label="Root Cause"
                name="root_cause"
                value={formData.root_cause}
                onChange={handleFormChange}
                multiline
                rows={2}
                placeholder="What caused the failure?"
                helperText={formData.error_log_id ? "💡 Auto-filled from error description" : ""}
              />
            </Grid>
            <Grid item xs={12}>
              <TextField
                fullWidth
                label="Problem Analysis"
                name="problem_analysis"
                value={formData.problem_analysis}
                onChange={handleFormChange}
                multiline
                rows={2}
                placeholder="Detailed analysis of the problem"
              />
            </Grid>

            <Grid item xs={12}>
              <Divider sx={{ my: 1 }} />
              <Typography variant="subtitle2" fontWeight={600} color="primary" gutterBottom>
                Solution
              </Typography>
            </Grid>
            <Grid item xs={12}>
              <TextField
                fullWidth
                label="Corrective Action"
                name="corrective_action"
                value={formData.corrective_action}
                onChange={handleFormChange}
                multiline
                rows={2}
                placeholder="Actions taken to fix the issue"
              />
            </Grid>
            <Grid item xs={12}>
              <TextField
                fullWidth
                label="Repair Procedure"
                name="repair_procedure"
                value={formData.repair_procedure}
                onChange={handleFormChange}
                multiline
                rows={3}
                placeholder="Step by step repair procedure"
              />
            </Grid>
            <Grid item xs={12}>
              <TextField
                fullWidth
                label="Solution Description"
                name="solution_description"
                value={formData.solution_description}
                onChange={handleFormChange}
                multiline
                rows={2}
                placeholder="Detailed solution description"
              />
            </Grid>

            <Grid item xs={12}>
              <Divider sx={{ my: 1 }} />
              <Typography variant="subtitle2" fontWeight={600} color="primary" gutterBottom>
                Additional Details
              </Typography>
            </Grid>
            <Grid item xs={12} md={4}>
              <TextField
                fullWidth
                label="Time Taken (minutes)"
                name="time_taken"
                type="number"
                value={formData.time_taken}
                onChange={handleFormChange}
                InputProps={{ inputProps: { min: 0 } }}
              />
            </Grid>
            <Grid item xs={12} md={4}>
              <FormControl fullWidth>
                <InputLabel>Spare Part Used</InputLabel>
                <Select
                  name="spare_part_used"
                  value={formData.spare_part_used}
                  onChange={handleFormChange}
                  label="Spare Part Used"
                >
                  <MenuItem value="No">No</MenuItem>
                  <MenuItem value="Yes">Yes</MenuItem>
                </Select>
              </FormControl>
            </Grid>
            <Grid item xs={12} md={4}>
              <FormControl fullWidth>
                <InputLabel>Status</InputLabel>
                <Select
                  name="status"
                  value={formData.status}
                  onChange={handleFormChange}
                  label="Status"
                  disabled={!isSuperAdmin}
                >
                  <MenuItem value="Pending">Pending</MenuItem>
                  <MenuItem value="Assigned">Assigned</MenuItem>
                  <MenuItem value="Accepted">Accepted</MenuItem>
                  <MenuItem value="In Progress">In Progress</MenuItem>
                  <MenuItem value="Waiting for Spare Parts">Waiting for Spare Parts</MenuItem>
                  <MenuItem value="Testing">Testing</MenuItem>
                  <MenuItem value="Completed">Completed</MenuItem>
                  <MenuItem value="Verified">Verified</MenuItem>
                  <MenuItem value="Resolved">Resolved</MenuItem>
                  <MenuItem value="Closed">Closed</MenuItem>
                </Select>
              </FormControl>
              {!isSuperAdmin && (
                <FormHelperText>Only Super Admin can change status</FormHelperText>
              )}
            </Grid>

            {/* CONDITIONAL SPARE PARTS FIELDS */}
            {showSparePartsFields && (
              <Grid item xs={12}>
                <Divider sx={{ my: 2 }} />
                <Typography variant="subtitle2" fontWeight={600} color="primary" gutterBottom>
                  Spare Parts Details
                </Typography>
                
                <Box sx={{ p: 2, bgcolor: '#f8f9fa', borderRadius: 2 }}>
                  <Grid container spacing={2}>
                    <Grid item xs={12} md={4}>
                      <TextField
                        fullWidth
                        size="small"
                        label="Part Name *"
                        name="part_name"
                        value={sparePartForm.part_name}
                        onChange={handleSparePartChange}
                        placeholder="e.g., Power Supply"
                      />
                    </Grid>
                    <Grid item xs={12} md={3}>
                      <TextField
                        fullWidth
                        size="small"
                        label="Part Number"
                        name="part_number"
                        value={sparePartForm.part_number}
                        onChange={handleSparePartChange}
                        placeholder="e.g., PSU-001"
                      />
                    </Grid>
                    <Grid item xs={12} md={2}>
                      <TextField
                        fullWidth
                        size="small"
                        label="Brand"
                        name="brand"
                        value={sparePartForm.brand}
                        onChange={handleSparePartChange}
                        placeholder="e.g., Siemens"
                      />
                    </Grid>
                    <Grid item xs={12} md={1}>
                      <TextField
                        fullWidth
                        size="small"
                        label="Qty"
                        name="quantity"
                        type="number"
                        value={sparePartForm.quantity}
                        onChange={handleSparePartChange}
                        InputProps={{ inputProps: { min: 1, step: 1 } }}
                      />
                    </Grid>
                    <Grid item xs={12} md={2}>
                      <TextField
                        fullWidth
                        size="small"
                        label="Unit Cost ($)"
                        name="unit_cost"
                        type="number"
                        value={sparePartForm.unit_cost}
                        onChange={handleSparePartChange}
                        InputProps={{ inputProps: { min: 0, step: 0.01 } }}
                      />
                    </Grid>
                    <Grid item xs={12} md={6}>
                      <TextField
                        fullWidth
                        size="small"
                        label="Installation Notes"
                        name="installation_notes"
                        value={sparePartForm.installation_notes}
                        onChange={handleSparePartChange}
                        placeholder="Any special instructions..."
                      />
                    </Grid>
                    <Grid item xs={12} md={2}>
                      <Button
                        fullWidth
                        variant="contained"
                        onClick={handleAddSparePart}
                        sx={{ height: '100%', bgcolor: '#0B5FA5' }}
                      >
                        Add
                      </Button>
                    </Grid>
                  </Grid>

                  {sparePartsList.length > 0 && (
                    <Box sx={{ mt: 2 }}>
                      <Typography variant="caption" color="textSecondary">
                        Added Parts ({sparePartsList.length})
                      </Typography>
                      <TableContainer component={Paper} variant="outlined" sx={{ mt: 1 }}>
                        <Table size="small">
                          <TableHead>
                            <TableRow>
                              <TableCell>Part Name</TableCell>
                              <TableCell>Part #</TableCell>
                              <TableCell>Brand</TableCell>
                              <TableCell align="center">Qty</TableCell>
                              <TableCell align="right">Cost</TableCell>
                              <TableCell align="right">Total</TableCell>
                              <TableCell align="center">Action</TableCell>
                            </TableRow>
                          </TableHead>
                          <TableBody>
                            {sparePartsList.map((part) => (
                              <TableRow key={part.id}>
                                <TableCell>{part.part_name}</TableCell>
                                <TableCell>{part.part_number || '-'}</TableCell>
                                <TableCell>{part.brand || '-'}</TableCell>
                                <TableCell align="center">
                                  {part.quantity}
                                </TableCell>
                                <TableCell align="right">${part.unit_cost.toFixed(2)}</TableCell>
                                <TableCell align="right" sx={{ fontWeight: 600 }}>
                                  ${part.total_cost.toFixed(2)}
                                </TableCell>
                                <TableCell align="center">
                                  <IconButton 
                                    size="small" 
                                    color="error" 
                                    onClick={() => handleRemoveSparePart(part.id)}
                                  >
                                    <Delete fontSize="small" />
                                  </IconButton>
                                </TableCell>
                              </TableRow>
                            ))}
                            <TableRow sx={{ bgcolor: '#f5f5f5' }}>
                              <TableCell colSpan={5} align="right" sx={{ fontWeight: 600 }}>
                                Total:
                              </TableCell>
                              <TableCell align="right" sx={{ fontWeight: 700, color: '#0B5FA5' }}>
                                ${sparePartsList.reduce((sum, p) => sum + p.total_cost, 0).toFixed(2)}
                              </TableCell>
                              <TableCell />
                            </TableRow>
                          </TableBody>
                        </Table>
                      </TableContainer>
                    </Box>
                  )}
                </Box>
              </Grid>
            )}

            <Grid item xs={12}>
              <TextField
                fullWidth
                label="Remarks"
                name="remarks"
                value={formData.remarks}
                onChange={handleFormChange}
                multiline
                rows={2}
                placeholder="Additional remarks"
              />
            </Grid>
          </Grid>
        </DialogContent>
        <DialogActions sx={{ p: 3 }}>
          <Button onClick={handleCloseDialog}>Cancel</Button>
          <Button 
            variant="contained" 
            onClick={handleSubmit} 
            sx={{ bgcolor: '#0B5FA5', '&:hover': { bgcolor: '#084a8a' } }}
          >
            {editingRepair ? 'Update Repair' : 'Record Repair'}
          </Button>
        </DialogActions>
      </Dialog>

      {/* View Dialog */}
      <Dialog open={openViewDialog} onClose={handleCloseView} maxWidth="md" fullWidth>
        <DialogTitle sx={{ bgcolor: '#0B5FA5', color: 'white' }}>
          <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
            <Typography variant="h6" fontWeight={600}>Repair Details</Typography>
            <Box>
              {isSuperAdmin && (
                <Chip label="Super Admin" size="small" color="warning" sx={{ mr: 1 }} />
              )}
              {isEngineer && (
                <Chip label="Engineer" size="small" color="info" sx={{ mr: 1 }} />
              )}
              <IconButton onClick={handleCloseView} sx={{ color: 'white' }}>
                <Close />
              </IconButton>
            </Box>
          </Box>
        </DialogTitle>
        <DialogContent dividers>
          {viewingRepair && (
            <Box>
              <Grid container spacing={2}>
                <Grid item xs={12}>
                  <Alert severity="info">
                    Repair record for <strong>{viewingRepair.equipment_name}</strong>
                    {isSuperAdmin && (
                      <Typography variant="caption" color="textSecondary" sx={{ display: 'block', mt: 1 }}>
                        👑 Super Admin - You can edit or delete this repair
                      </Typography>
                    )}
                    {isEngineer && (
                      <Typography variant="caption" color="textSecondary" sx={{ display: 'block', mt: 1 }}>
                        🔧 Engineer - You can view this repair. Only Super Admin can edit or delete.
                        {viewingRepair.engineer_id === user?.id && (
                          <span style={{ color: '#0B5FA5', fontWeight: 600 }}> (Your Repair)</span>
                        )}
                      </Typography>
                    )}
                  </Alert>
                </Grid>
                <Grid item xs={12} md={6}>
                  <Typography variant="body2" color="textSecondary">Equipment</Typography>
                  <Typography variant="body1" fontWeight={500}>{viewingRepair.equipment_name || 'N/A'}</Typography>
                </Grid>
                <Grid item xs={12} md={6}>
                  <Typography variant="body2" color="textSecondary">Status</Typography>
                  <Chip 
                    label={viewingRepair.status} 
                    size="small"
                    color={
                      viewingRepair.status === 'Completed' || viewingRepair.status === 'Verified' || viewingRepair.status === 'Resolved' ? 'success' :
                      viewingRepair.status === 'Pending' ? 'default' :
                      viewingRepair.status === 'In Progress' ? 'info' :
                      viewingRepair.status === 'Assigned' || viewingRepair.status === 'Accepted' ? 'primary' :
                      viewingRepair.status === 'Waiting for Spare Parts' ? 'warning' :
                      viewingRepair.status === 'Testing' ? 'secondary' :
                      viewingRepair.status === 'Closed' ? 'default' : 'default'
                    }
                  />
                </Grid>
                <Grid item xs={12} md={6}>
                  <Typography variant="body2" color="textSecondary">Engineer</Typography>
                  <Typography variant="body1">{viewingRepair.engineer_name || 'N/A'}</Typography>
                </Grid>
                <Grid item xs={12} md={6}>
                  <Typography variant="body2" color="textSecondary">Time Taken</Typography>
                  <Typography variant="body1">{viewingRepair.time_taken || 'N/A'} minutes</Typography>
                </Grid>
                <Grid item xs={12} md={6}>
                  <Typography variant="body2" color="textSecondary">Spare Part Used</Typography>
                  <Typography variant="body1">{viewingRepair.spare_part_used || 'No'}</Typography>
                </Grid>
                <Grid item xs={12} md={6}>
                  <Typography variant="body2" color="textSecondary">Repair Date</Typography>
                  <Typography variant="body1">{viewingRepair.repair_date ? new Date(viewingRepair.repair_date).toLocaleString() : 
                    viewingRepair.created_at ? new Date(viewingRepair.created_at).toLocaleString() : '-'}</Typography>
                </Grid>

                <Grid item xs={12}>
                  <Divider sx={{ my: 1 }} />
                </Grid>
                <Grid item xs={12}>
                  <Typography variant="subtitle2" fontWeight={600} gutterBottom>Root Cause</Typography>
                  <Typography variant="body2" paragraph>{viewingRepair.root_cause || 'Not specified'}</Typography>
                </Grid>
                <Grid item xs={12}>
                  <Typography variant="subtitle2" fontWeight={600} gutterBottom>Problem Analysis</Typography>
                  <Typography variant="body2" paragraph>{viewingRepair.problem_analysis || 'Not specified'}</Typography>
                </Grid>
                <Grid item xs={12}>
                  <Typography variant="subtitle2" fontWeight={600} gutterBottom>Corrective Action</Typography>
                  <Typography variant="body2" paragraph>{viewingRepair.corrective_action || 'Not specified'}</Typography>
                </Grid>
                <Grid item xs={12}>
                  <Typography variant="subtitle2" fontWeight={600} gutterBottom>Repair Procedure</Typography>
                  <Paper sx={{ p: 2, bgcolor: '#f5f5f5', borderRadius: 1 }}>
                    <Typography variant="body2" sx={{ whiteSpace: 'pre-line' }}>
                      {viewingRepair.repair_procedure || 'Not specified'}
                    </Typography>
                  </Paper>
                </Grid>
                {viewingRepair.solution_description && (
                  <Grid item xs={12}>
                    <Typography variant="subtitle2" fontWeight={600} gutterBottom>Solution Description</Typography>
                    <Typography variant="body2">{viewingRepair.solution_description}</Typography>
                  </Grid>
                )}
                {viewingRepair.remarks && (
                  <Grid item xs={12}>
                    <Typography variant="subtitle2" fontWeight={600} gutterBottom>Remarks</Typography>
                    <Typography variant="body2">{viewingRepair.remarks}</Typography>
                  </Grid>
                )}
              </Grid>
            </Box>
          )}
        </DialogContent>
        <DialogActions sx={{ p: 3 }}>
          <Button onClick={handleCloseView}>Close</Button>
          {/* ✅ ONLY Super Admin can edit */}
          {isSuperAdmin && viewingRepair && (
            <Button
              variant="contained"
              color="info"
              onClick={() => {
                handleCloseView()
                handleOpenDialog(viewingRepair)
              }}
              startIcon={<Edit />}
              sx={{ bgcolor: '#0B5FA5', '&:hover': { bgcolor: '#084a8a' }, mr: 1 }}
            >
              Edit
            </Button>
          )}
          {/* ✅ ONLY Super Admin can delete */}
          {isSuperAdmin && viewingRepair && (
            <Button
              variant="contained"
              color="error"
              onClick={() => {
                handleDelete(viewingRepair.id)
                handleCloseView()
              }}
              startIcon={<Delete />}
            >
              Delete
            </Button>
          )}
        </DialogActions>
      </Dialog>
    </Box>
  )
}

export default Repairs